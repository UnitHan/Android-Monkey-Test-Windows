"""Contract-checking API client.

Every response is validated against the OpenAPI document generated by the app:
  - the status code must be documented for that operation,
  - the body must match the documented schema (JSON / problem+json).
Every X-Request-ID is recorded so failing tests can print the matching API logs.
"""

from __future__ import annotations

import re
import time
from dataclasses import asdict
from typing import Any

import jsonschema
from fastapi.testclient import TestClient
from httpx import Response

from monkey_api.core.logging import LogQuery, LogStore


class ContractViolation(AssertionError):
    pass


class ContractClient:
    def __init__(self, client: TestClient, log_store: LogStore, prefix: str = "/api/v1") -> None:
        self.client = client
        self.log_store = log_store
        self.prefix = prefix
        self.spec: dict[str, Any] = client.app.openapi()  # type: ignore[attr-defined]
        self.request_ids: list[str] = []
        self._ops = [
            (re.compile("^" + re.sub(r"\{[^}]+\}", r"[^/]+", path) + "$"), path) for path in self.spec["paths"]
        ]

    # ---- HTTP verbs ----

    def get(self, path: str, **kw: Any) -> Response:
        return self.request("GET", path, **kw)

    def post(self, path: str, **kw: Any) -> Response:
        return self.request("POST", path, **kw)

    def delete(self, path: str, **kw: Any) -> Response:
        return self.request("DELETE", path, **kw)

    def request(self, method: str, path: str, **kw: Any) -> Response:
        resp = self.client.request(method, self.prefix + path, **kw)
        rid = resp.headers.get("x-request-id")
        if not rid:
            raise ContractViolation(f"{method} {path}: missing X-Request-ID header")
        self.request_ids.append(rid)
        self.check(method, self.prefix + path, resp)
        return resp

    # ---- contract ----

    def operation(self, method: str, url_path: str) -> dict[str, Any]:
        bare = url_path.split("?")[0]
        matches = [tpl for rx, tpl in self._ops if rx.match(bare)]
        # prefer literal paths over templated ones (/devices/connect vs /devices/{serial})
        matches.sort(key=lambda t: t.count("{"))
        for tpl in matches:
            op = self.spec["paths"][tpl].get(method.lower())
            if op is not None:
                return op
        raise ContractViolation(f"{method} {bare}: not in OpenAPI contract")

    def check(self, method: str, url_path: str, resp: Response) -> None:
        op = self.operation(method, url_path)
        status = str(resp.status_code)
        responses = op.get("responses", {})
        if status not in responses:
            raise ContractViolation(
                f"{method} {url_path}: status {status} not documented (documented: {sorted(responses)})\n"
                f"body: {resp.text[:500]}"
            )
        content = responses[status].get("content", {})
        ctype = resp.headers.get("content-type", "").split(";")[0]
        if ctype not in ("application/json", "application/problem+json"):
            return
        schema_holder = content.get(ctype) or content.get("application/json")
        if not schema_holder or "schema" not in schema_holder:
            if ctype == "application/problem+json":
                schema_holder = {"schema": {"$ref": "#/components/schemas/Problem"}}
            else:
                return
        schema = {**schema_holder["schema"], "components": self.spec.get("components", {})}
        try:
            jsonschema.Draft202012Validator(schema).validate(resp.json())
        except jsonschema.ValidationError as exc:
            raise ContractViolation(
                f"{method} {url_path} -> {status}: body violates contract at {list(exc.absolute_path)}: {exc.message}"
            ) from exc

    # ---- diagnostics ----

    def logs_for_requests(self) -> str:
        lines: list[str] = []
        for rid in self.request_ids:
            for r in self.log_store.query(LogQuery(request_id=rid, limit=0)):
                lines.append(_fmt(asdict(r)))
        return "\n".join(lines)

    def problem_logs(self) -> str:
        records = self.log_store.query(LogQuery(level="WARNING", limit=0))
        return "\n".join(_fmt(asdict(r)) for r in records)

    def wait_state(self, session_id: str, states: set[str], timeout_s: float = 10.0) -> dict[str, Any]:
        deadline = time.monotonic() + timeout_s
        while True:
            body = self.get(f"/sessions/{session_id}").json()
            if body["state"] in states:
                return body
            if time.monotonic() > deadline:
                raise AssertionError(f"session {session_id} stuck in {body['state']} (wanted {states})")
            time.sleep(0.05)


def _fmt(r: dict[str, Any]) -> str:
    return (
        f"#{r['seq']} {r['at']} {r['level']:<7} {r['source']:<7} rid={r['request_id']} sid={r['session_id']} "
        f"{r['message']} {r['data'] or ''}"
    )
